// Report generation utilities — CSV and PDF (printable) exports.

export function exportCSV(filename: string, rows: Record<string, unknown>[]) {
  if (!rows.length) return;
  const headers = Object.keys(rows[0]);
  const csv = [
    headers.join(','),
    ...rows.map((row) =>
      headers.map((h) => {
        const val = row[h];
        if (val === null || val === undefined) return '';
        const str = typeof val === 'object' ? JSON.stringify(val) : String(val);
        return `"${str.replace(/"/g, '""')}"`;
      }).join(',')
    ),
  ].join('\n');

  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
  downloadBlob(blob, filename);
}

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function exportJSON(filename: string, data: unknown) {
  const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
  downloadBlob(blob, filename);
}

// Generate a printable PDF report by opening a new window and triggering print
export function exportPDFReport(title: string, sections: { heading: string; body: string }[]) {
  const win = window.open('', '_blank', 'width=800,height=900');
  if (!win) return;
  const html = `
  <!doctype html><html><head><title>${title}</title>
  <style>
    body{font-family:Arial,Helvetica,sans-serif;padding:40px;color:#0f172a;max-width:800px;margin:auto}
    h1{color:#0369a1;border-bottom:3px solid #0ea5e9;padding-bottom:10px}
    h2{color:#075985;margin-top:28px}
    .meta{color:#64748b;font-size:13px;margin-bottom:24px}
    .badge{display:inline-block;background:#e0f2fe;color:#0369a1;padding:4px 12px;border-radius:999px;font-size:12px;margin:2px}
    .footer{margin-top:48px;padding-top:16px;border-top:1px solid #e2e8f0;color:#94a3b8;font-size:11px}
    table{width:100%;border-collapse:collapse;margin:12px 0}
    td,th{border:1px solid #e2e8f0;padding:8px;text-align:left;font-size:13px}
    th{background:#f0f9ff}
  </style></head><body>
  <h1>${title}</h1>
  <div class="meta">Q-MedLab Quantum Medical Laboratory | Generated: ${new Date().toLocaleString()}</div>
  ${sections.map((s) => `<h2>${s.heading}</h2><div>${s.body}</div>`).join('')}
  <div class="footer">This report was generated by Q-MedLab for educational and research purposes only. Not for clinical use.</div>
  </body></html>`;
  win.document.write(html);
  win.document.close();
  setTimeout(() => win.print(), 500);
}

export function formatDate(iso: string): string {
  return new Date(iso).toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' });
}
